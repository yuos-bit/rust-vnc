//! Versioned DTOs shared by the pairing backend and both desktop roles.

use serde::{Deserialize, Serialize};

pub const API_VERSION: &str = "v1";

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ErrorBody {
    pub code: String,
    pub message: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ApiError {
    pub error: ErrorBody,
}

impl ApiError {
    pub fn new(code: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            error: ErrorBody {
                code: code.into(),
                message: message.into(),
            },
        }
    }
}

/// Generated by the controlled endpoint; the server returns the only copy of
/// the plaintext password and agent secret.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegisterDeviceRequest {
    pub name: String,
    pub platform: String,
    pub fingerprint: String,
    pub version: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegisterDeviceResponse {
    pub device_id: String,
    pub device_code: String,
    pub password: String,
    pub agent_secret: String,
    pub protocol_version: u16,
    pub headscale: Option<HeadscaleBootstrap>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HeadscaleBootstrap {
    pub control_url: String,
    pub preauth_key: String,
    pub hostname: String,
    pub derp_url: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HeartbeatRequest {
    pub device_code: String,
    pub agent_secret: String,
    pub tailscale_ip: Option<String>,
    pub listen_port: u16,
    pub version: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HeartbeatResponse {
    pub online: bool,
    pub server_time: i64,
    pub paired_controllers: Vec<PairedController>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PairedController {
    pub token_id: String,
    pub controller_id: String,
    pub name: String,
    pub platform: String,
    pub paired_at: i64,
    pub last_seen: Option<i64>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PairRequest {
    pub device_code: String,
    pub password: String,
    pub controller_id: String,
    pub controller_name: String,
    pub platform: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PairResponse {
    pub token: String,
    pub token_id: String,
    pub device_code: String,
    pub device_name: String,
    pub tailscale_ip: Option<String>,
    pub online: bool,
    pub server_version: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConnectRequest {
    pub device_code: String,
    pub token: String,
    pub controller_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConnectResponse {
    pub device_code: String,
    pub device_name: String,
    pub tailscale_ip: String,
    pub port: u16,
    pub online: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerifySessionRequest {
    pub device_code: String,
    pub agent_secret: String,
    pub token: String,
    pub controller_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerifySessionResponse {
    pub valid: bool,
    pub token_id: Option<String>,
    pub controller_name: Option<String>,
    pub expires_at: Option<i64>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RevokeTokenRequest {
    pub device_code: String,
    pub agent_secret: String,
    pub token_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChangePasswordRequest {
    pub device_code: String,
    pub agent_secret: String,
    /// Omit to have the server generate a fresh random password.
    pub new_password: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChangePasswordResponse {
    pub password: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ServerInfo {
    pub version: String,
    pub protocol_version: u16,
    pub headscale_configured: bool,
}

/// A controller (phone or PC) asks the backend for a short-lived pre-auth key
/// so its embedded tsnet/VpnService network layer can join the tailnet.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EnrollControllerRequest {
    pub name: String,
    pub platform: String,
    pub fingerprint: String,
    pub controller_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EnrollControllerResponse {
    pub preauth_key: String,
    pub control_url: String,
    pub hostname: String,
    pub derp_url: Option<String>,
}

